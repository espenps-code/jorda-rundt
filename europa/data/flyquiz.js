// ---------- trekking (lik i elevsiden og banken) ----------
function hash(str) { let h = 2166136261; for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }
function rng(seed) { let s = hash(String(seed)) || 1; return () => { s ^= s << 13; s >>>= 0; s ^= s >> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; }; }
function stokk(r, a) { a = [...a]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }

export const MAKS_SPORSMAL = 60;

/** Lager spørsmålsrekka for én flytur. Samme frø gir samme rekke (banken kan sjekke svarene). */
export function flySporsmal(fro, antall = MAKS_SPORSMAL) {
  const r = rng('fly-' + fro);
  const rekkefolge = Object.fromEntries(KATEGORIER.map((k) => [k.id, stokk(rng(`fly-${fro}-${k.id}`), SPORSMAL[k.id].map((_, i) => i))]));
  const peker = Object.fromEntries(KATEGORIER.map((k) => [k.id, 0]));
  const ut = [];
  for (let n = 0; n < antall; n++) {
    const kat = KATEGORIER[Math.floor(r() * KATEGORIER.length)];
    const liste = rekkefolge[kat.id];
    const [tekst, riktig, ...feil] = SPORSMAL[kat.id][liste[peker[kat.id]++ % liste.length]];
    ut.push({ kategori: kat.id, tekst, valg: stokk(r, [riktig, ...feil]), svar: riktig });
  }
  return ut;
}

/** Teller riktige svar. svar = liste med valgte alternativer i rekkefølge. */
export function rettFlyquiz(fro, svar = []) {
  const s = flySporsmal(fro, Math.min(svar.length, MAKS_SPORSMAL));
  return s.filter((q, i) => svar[i] === q.svar).length;
}

